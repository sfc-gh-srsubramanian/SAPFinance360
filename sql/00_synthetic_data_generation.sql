-- 4. JOURNAL ENTRY HEADERS (5,000 documents)
-- =============================================================================
CREATE OR REPLACE TABLE SAP_FINANCE_360.SAP_BDC_L0.JOURNALENTRY (
  COMPANYCODE VARCHAR(4),
  FISCALYEAR VARCHAR(4),
  ACCOUNTINGDOCUMENT VARCHAR(10),
  DOCUMENTDATE DATE,
  POSTINGDATE DATE,
  ACCOUNTINGDOCUMENTTYPE VARCHAR(2),
  ISREVERSAL BOOLEAN,
  ISREVERSED BOOLEAN,
  DOCUMENTHEADERTEXT VARCHAR(100),
  CREATEDBYUSER VARCHAR(12),
  LASTCHANGEDATE DATE
);

INSERT INTO SAP_FINANCE_360.SAP_BDC_L0.JOURNALENTRY
WITH docs AS (
  SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) AS rn FROM TABLE(GENERATOR(ROWCOUNT=>5000))
)
SELECT
  CASE WHEN MOD(d.rn, 10) < 5 THEN '1000'
       WHEN MOD(d.rn, 10) < 8 THEN '2100'
       ELSE '5000' END AS COMPANYCODE,
  CASE WHEN MOD(d.rn, 3) = 0 THEN '2023'
       WHEN MOD(d.rn, 3) = 1 THEN '2024'
       ELSE '2025' END AS FISCALYEAR,
  LPAD(d.rn::STRING, 10, '0') AS ACCOUNTINGDOCUMENT,
  DATEADD('day', -MOD(d.rn * 7, 900), '2025-06-30')::DATE AS DOCUMENTDATE,
  DATEADD('day', -MOD(d.rn * 7, 900) + MOD(d.rn, 3), '2025-06-30')::DATE AS POSTINGDATE,
  CASE MOD(d.rn, 5)
    WHEN 0 THEN 'SA' WHEN 1 THEN 'KR' WHEN 2 THEN 'DR'
    WHEN 3 THEN 'AB' ELSE 'KZ' END AS ACCOUNTINGDOCUMENTTYPE,
  CASE WHEN MOD(d.rn, 50) = 0 THEN TRUE ELSE FALSE END AS ISREVERSAL,
  CASE WHEN MOD(d.rn, 50) = 1 THEN TRUE ELSE FALSE END AS ISREVERSED,
  CASE MOD(d.rn, 5)
    WHEN 0 THEN 'GL posting'
    WHEN 1 THEN 'Vendor invoice'
    WHEN 2 THEN 'Customer invoice'
    WHEN 3 THEN 'Clearing'
    ELSE 'Payment' END AS DOCUMENTHEADERTEXT,
  'BATCH_USER' AS CREATEDBYUSER,
  DATEADD('day', -MOD(d.rn * 7, 900) + MOD(d.rn, 3), '2025-06-30')::DATE AS LASTCHANGEDATE
FROM docs d;

